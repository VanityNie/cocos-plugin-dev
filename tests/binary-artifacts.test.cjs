'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const windows = require('../lib/windows.cjs');
const support = require('../templates/common/editor/plugin-support.cjs');
const binary = require('../lib/binary-artifacts.cjs');

for (const buildType of ['Debug', 'RelWithDebInfo', 'Release']) test(`真实 CMake ${buildType} 编译导出静态依赖、DLL、WHOLEARCHIVE 与公开编译设置，并在独立目录消费`, { skip: process.env.COCOS_PLUGIN_NATIVE_TESTS !== '1', timeout: 120000 }, async t => {
    const parent = path.resolve(__dirname, '../.local');
    fs.mkdirSync(parent, { recursive: true });
    const root = fs.mkdtempSync(path.join(parent, 'binary-artifacts-'));
    t.diagnostic(root);
    const source = path.join(root, 'producer');
    fs.cpSync(path.join(__dirname, 'fixtures/binary-build'), source, { recursive: true });
    fs.mkdirSync(path.join(source, 'assets'));
    support.writeJson(path.join(source, 'package.json'), { name: 'binary-artifact-check' });
    const report = await windows.doctor({ projectPath: source });
    assert.equal(report.ok, true, JSON.stringify(report.checks));
    const internal = windows._internal;
    const environment = await internal.execute(process.env.ComSpec, ['/d', '/s', '/v:off', '/c', internal.vsBootstrapCommand(report.tools.vsDevCmd)], { windowsVerbatimArguments: true });
    const env = internal.parseEnvironment(environment.output);
    env.VSLANG = '1033';
    const state = { projectPath: source, buildDir: path.join(source, '.plugin-dev/build'), buildType, tools: report.tools, enginePath: report.host.enginePath };
    env.LIB = `${state.buildDir};${env.LIB}`;
    fs.mkdirSync(path.join(state.buildDir, '.cmake/api/v1/query'), { recursive: true });
    fs.writeFileSync(path.join(state.buildDir, '.cmake/api/v1/query/codemodel-v2'), '');
    const cmakeArgs = ['-G', 'Ninja', `-DCMAKE_BUILD_TYPE=${buildType}`, `-DCMAKE_MAKE_PROGRAM=${report.tools.ninja}`, `-DCOCOS_X_PATH=${path.join(report.host.enginePath, 'native')}`];
    await internal.execute(report.tools.cmake, ['-S', source, '-B', state.buildDir, ...cmakeArgs,
        `-DBINARY_METADATA_MODULE=${path.resolve(__dirname, '../lib/cmake/binary-build.cmake')}`, `-DEXPORT_IPO=${buildType === 'Release' ? 'ON' : 'OFF'}`], { env });
    await internal.execute(report.tools.cmake, ['--build', state.buildDir], { env });
    state.builtAt = new Date().toISOString();
    const records = { example: { enabled: true, detached: false, target: 'binary_plugin', sourcePath: source, nativeFingerprint: support.nativeFingerprint(source) } };
    support.writeJson(path.join(source, '.plugin-dev/state.json'), { schemaVersion: 1, plugins: records });
    support.writeJson(path.join(source, '.plugin-dev/windows.json'), state);
    binary.recordBinaryBuild(state, records);
    const artifacts = binary.readBinaryArtifacts({ projectPath: source, name: 'example' });
    assert.equal(artifacts.buildType, buildType);
    assert.equal(artifacts.files.filter(file => /\.lib$/i.test(file.source)).length, 6);
    assert.equal(artifacts.files.some(file => /\.pdb$/i.test(file.source)), buildType !== 'Release');
    assert.equal(artifacts.manifest.interproceduralOptimization, buildType === 'Release');
    assert.equal(artifacts.files.some(file => path.basename(file.source) === 'binary_base.lib'), false);
    assert.equal(artifacts.files.some(file => path.basename(file.source) === 'binary_external.lib'), true);
    assert.deepEqual(artifacts.manifest.compileDefinitions.sort(), ['CPD_ESCAPED="a\\\\b"', 'CPD_PUBLIC_VALUE=7', 'FOO=1']);
    assert.equal(artifacts.runtimeFiles.length, 1);
    assert.equal(binary.readBinaryArtifacts({ projectPath: source, name: 'example', buildType: buildType.toLowerCase() }).buildType, buildType);
    assert.throws(() => binary.readBinaryArtifacts({ projectPath: source, name: 'example', buildType: 'Shipping' }), /buildType/);
    assert.ok(artifacts.cmake.includes('/WHOLEARCHIVE:'));
    assert.ok(artifacts.cmake.includes('CPD_PUBLIC_VALUE=7'));
    assert.ok(artifacts.cmake.includes('"FOO=1"'));
    assert.ok(artifacts.cmake.includes('/Zc:__cplusplus'));
    assert.equal(JSON.stringify(artifacts.manifest).includes(root), false);
    const publication = path.join(root, 'publication');
    fs.cpSync(path.join(source, 'native/include'), path.join(publication, 'native/windows/lib/include/plugin'), { recursive: true });
    for (const file of artifacts.files) {
        const destination = path.join(publication, file.packagePath);
        fs.mkdirSync(path.dirname(destination), { recursive: true });
        fs.copyFileSync(file.source, destination);
    }
    const config = path.join(publication, 'native/windows/binary_plugin-config.cmake');
    fs.writeFileSync(config, artifacts.cmake);
    const consumerSource = path.join(root, 'consumer');
    fs.mkdirSync(path.join(consumerSource, 'native'), { recursive: true });
    for (const relative of ['CMakeLists.txt', 'native/base.cpp', 'native/main.cpp']) fs.copyFileSync(path.join(source, relative), path.join(consumerSource, relative));
    const incompatibleType = buildType === 'Debug' ? 'Release' : 'Debug';
    assert.throws(() => binary.readBinaryArtifacts({ projectPath: source, name: 'example', buildType: incompatibleType }), /最近成功构建配置/);
    support.writeJson(path.join(source, '.plugin-dev/windows.json'), { ...state, builtAt: undefined });
    assert.throws(() => binary.readBinaryArtifacts({ projectPath: source, name: 'example' }), /构建状态不匹配/);
    support.writeJson(path.join(source, '.plugin-dev/windows.json'), state);
    const sourceFile = path.join(source, 'native/plugin.cpp');
    const sourceContent = fs.readFileSync(sourceFile);
    fs.appendFileSync(sourceFile, '\n');
    assert.throws(() => binary.readBinaryArtifacts({ projectPath: source, name: 'example' }), /插件 example 已发生变化/);
    fs.writeFileSync(sourceFile, sourceContent);
    const missingLibrary = artifacts.files[0].source;
    fs.renameSync(missingLibrary, `${missingLibrary}.held`);
    assert.throws(() => binary.readBinaryArtifacts({ projectPath: source, name: 'example' }), /二进制构建产物不存在/);
    fs.renameSync(`${missingLibrary}.held`, missingLibrary);
    fs.appendFileSync(artifacts.files[0].source, 'changed');
    assert.throws(() => binary.readBinaryArtifacts({ projectPath: source, name: 'example' }), /构建产物已发生变化/);
    const consumerBuild = path.join(root, 'consumer-build');
    fs.mkdirSync(consumerBuild);
    for (const file of artifacts.runtimeFiles) fs.copyFileSync(file.source, path.join(consumerBuild, file.target));
    // 作者构建目录不可访问时，消费项目必须仍可编译和运行。
    fs.renameSync(source, path.join(root, 'producer-unavailable'));
    await internal.execute(report.tools.cmake, ['-S', consumerSource, '-B', consumerBuild, ...cmakeArgs, `-DPACKAGE_CONFIG=${config}`], { env });
    const consumerResult = await internal.execute(report.tools.cmake, ['--build', consumerBuild], { env });
    assert.doesNotMatch(consumerResult.output, /LNK4099/);
    const result = await internal.execute(path.join(consumerBuild, 'binary_consumer.exe'), [], { env });
    assert.match(result.output, /Binary result=220/);
    const multipleBuild = path.join(root, 'multi-config-build');
    await internal.execute(report.tools.cmake, ['-S', consumerSource, '-B', multipleBuild, ...cmakeArgs, '-G', 'Ninja Multi-Config', `-DPACKAGE_CONFIG=${config}`], { env });
    await internal.execute(report.tools.cmake, ['--build', multipleBuild, '--config', buildType], { env });
    const mismatch = new RegExp(`二进制插件要求 ${buildType} 构建配置`);
    await assert.rejects(internal.execute(report.tools.cmake, ['--build', multipleBuild, '--config', incompatibleType], { env }), mismatch);
    await internal.execute(report.tools.cmake, ['-S', consumerSource, '-B', consumerBuild, ...cmakeArgs, `-DCMAKE_BUILD_TYPE=${incompatibleType}`, `-DPACKAGE_CONFIG=${config}`], { env });
    await assert.rejects(internal.execute(report.tools.cmake, ['--build', consumerBuild], { env }), mismatch);
});
